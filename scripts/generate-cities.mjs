// Continents to skip (Antarctica entries are generally not useful for users)
const SKIP_CONTINENTS = new Set(['Antarctica'])

// Slugify: "New York City" → "new-york-city", drops non-ascii
function slugify(str) {
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')  // strip diacritics
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

// ID from timezone name: "America/New_York" → "america-new-york"
function tzToId(name) {
  return name.toLowerCase().replace(/\//g, '-').replace(/_/g, '-')
}

const timezones = getTimeZones()
const cities = []

for (const tz of timezones) {
  if (SKIP_CONTINENTS.has(tz.continentName)) continue

  const coords = COORDS[tz.name]
  if (!coords) {
    console.warn(`No coordinates for ${tz.name} — skipping`)
    continue
  }

  const cityName = tz.mainCities[0]
  cities.push({
    id: tzToId(tz.name),
    name: cityName,
    country: tz.countryName,
    countryCode: tz.countryCode,
    timezone: tz.name,
    lat: coords[0],
    lng: coords[1],
  })
}

